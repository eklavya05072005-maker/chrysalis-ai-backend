"""Pydantic schemas for Module W (Adaptive Requirement Wizard) and Module K (Spec Confirmer).

Enables context-aware requirement clarification and confirmed specification synthesis.
"""

from __future__ import annotations
from typing import Any, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field, model_validator

from backend.app.schemas.common import EvidenceReference
from backend.app.schemas.analysis import (
    Requirement,
    FunctionalRequirement,
    NonFunctionalRequirement,
    SoftwareModule,
    Workflow,
    BusinessRule,
    RiskAmbiguity,
)


class WizardOption(BaseModel):
    """An individual selectable option in an adaptive wizard question."""
    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    option_id: str = Field(..., description="Unique option key, e.g. 'opt_auto_approval'")
    text: str = Field(default="", description="Clear human-readable description of this choice")
    impact_summary: str = Field(
        default="",
        description="Architectural implication of selecting this option (e.g. adds gateway checkpoint)",
    )
    label: Optional[str] = Field(default=None, description="Optional label alias")
    description: Optional[str] = Field(default=None, description="Optional description alias")
    architectural_impact: Optional[str] = Field(default=None, description="Optional impact alias")

    @model_validator(mode="after")
    def sync_aliases(self) -> "WizardOption":
        if not self.text:
            self.text = self.label or self.description or self.option_id
        if not self.impact_summary:
            self.impact_summary = self.architectural_impact or "Architectural impact consideration"
        if not self.label:
            self.label = self.text
        if not self.description:
            self.description = self.text
        if not self.architectural_impact:
            self.architectural_impact = self.impact_summary
        return self


class WizardQuestion(BaseModel):
    """A context-aware question generated by Module W."""
    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    question_id: str = Field(..., description="Unique question identifier, e.g. 'Q-AUTONOMY'")
    category: Literal["goal", "autonomy", "connectors", "data_mode", "priority", "constraints"] = Field(
        ...,
        description="Design aspect targeted by this question",
    )
    prompt: str = Field(default="", description="The question text presented to the engineer or operator")
    why_it_matters: str = Field(
        default="",
        description="Explanation of why this decision materially affects system design",
    )
    options: list[WizardOption] = Field(
        ...,
        min_length=2,
        description="Curated multiple choice answers",
    )
    allow_custom: bool = Field(
        default=True,
        description="Whether a custom free-form answer is supported",
    )
    question_text: Optional[str] = Field(default=None, description="Prompt alias")
    reason: Optional[str] = Field(default=None, description="Why it matters alias")
    allows_custom: Optional[bool] = Field(default=None, description="Allow custom alias")

    @model_validator(mode="after")
    def sync_aliases(self) -> "WizardQuestion":
        if not self.prompt:
            self.prompt = self.question_text or "Please clarify requirement"
        if not self.why_it_matters:
            self.why_it_matters = self.reason or "Impacts system architecture"
        if not self.question_text:
            self.question_text = self.prompt
        if not self.reason:
            self.reason = self.why_it_matters
        if self.allows_custom is not None:
            self.allow_custom = self.allows_custom
        else:
            self.allows_custom = self.allow_custom
        return self


class WizardQuestionnaire(BaseModel):
    """Suite of 3-5 adaptive questions tailored to the analyzed software specification."""
    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    project_name: str = Field(..., description="Target project name")
    summary_context: str = Field(default="", description="Brief context summarizing the extracted domain")
    questions: list[WizardQuestion] = Field(
        ...,
        min_length=3,
        max_length=5,
        description="Set of 3 to 5 high-impact design questions",
    )
    notes: Optional[str] = Field(default=None, description="Summary context alias")

    @model_validator(mode="after")
    def sync_aliases(self) -> "WizardQuestionnaire":
        if not self.summary_context:
            self.summary_context = self.notes or f"Context for {self.project_name}"
        if not self.notes:
            self.notes = self.summary_context
        return self


class WizardAnswer(BaseModel):
    """User answer for an individual wizard question."""
    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    question_id: str = Field(..., description="Referenced question ID")
    selected_option_ids: list[str] = Field(
        default_factory=list,
        description="IDs of selected multiple-choice options",
    )
    selected_option_id: Optional[str] = Field(
        default=None,
        description="Single selected option ID alias",
    )
    custom_answer: str | None = Field(
        default=None,
        description="Optional free-form explanation or custom specification override",
    )
    answer_summary: Optional[str] = Field(
        default=None,
        description="Summary description of selected answer",
    )

    @model_validator(mode="after")
    def sync_aliases(self) -> "WizardAnswer":
        if self.selected_option_id and self.selected_option_id not in self.selected_option_ids:
            self.selected_option_ids.append(self.selected_option_id)
        elif self.selected_option_ids and not self.selected_option_id:
            self.selected_option_id = self.selected_option_ids[0]
        return self


class WizardAnswerSubmission(BaseModel):
    """Collection of user responses to the adaptive questionnaire."""
    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    project_name: Optional[str] = Field(default=None, description="Optional project name")
    answers: list[WizardAnswer] = Field(
        default_factory=list,
        description="Answers for the questionnaire",
    )
    additional_notes: str | None = Field(
        default=None,
        description="Optional overall constraints or requirements clarifications",
    )


class ConfirmedProjectSpec(BaseModel):
    """Confirmed software specification synthesized from analysis and user answers.
    
    Serves as the single source of truth for downstream verdict and architecture generation.
    """
    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    project_name: str = Field(..., description="Project name")
    primary_goal: str = Field(default="", description="Confirmed primary business or technical capability")
    executive_summary: Optional[str] = Field(default=None, description="Executive summary alias")
    autonomy_boundary: Literal[
        "suggest_only",
        "human_approval_for_sensitive_actions",
        "autonomous_low_risk",
    ] = Field(
        default="human_approval_for_sensitive_actions",
        description="Upper boundary of autonomous execution permitted",
    )
    data_mode: Literal["synthetic", "anonymized", "approved_live"] = Field(
        default="synthetic",
        description="Target operating data environment",
    )
    connector_preferences: list[Literal["mcp", "rest_api", "database", "custom_sdk"]] = Field(
        default_factory=lambda: ["rest_api", "database"],
        description="Approved integration interface protocols",
    )
    priorities: list[str] = Field(
        default_factory=list,
        description="Key engineering tradeoffs (e.g. accuracy, latency, cost)",
    )
    constraints: dict[str, Any] = Field(
        default_factory=dict,
        description="Technical and policy guardrails",
    )
    clarified_parameters: dict[str, Any] = Field(
        default_factory=dict,
        description="Key-value pairs of clarified wizard decisions",
    )
    confirmed_requirements: list[Requirement] = Field(
        default_factory=list,
        description="Validated functional and non-functional requirements with citations preserved",
    )
    functional_requirements: list[FunctionalRequirement] = Field(
        default_factory=list,
        description="Functional requirements list",
    )
    non_functional_requirements: list[NonFunctionalRequirement] = Field(
        default_factory=list,
        description="Non-functional requirements list",
    )
    modules: list[SoftwareModule] = Field(
        default_factory=list,
        description="Software modules list",
    )
    workflows: list[Workflow] = Field(
        default_factory=list,
        description="Workflows list",
    )
    business_rules: list[BusinessRule] = Field(
        default_factory=list,
        description="Business rules list",
    )
    risks_and_ambiguities: list[RiskAmbiguity] = Field(
        default_factory=list,
        description="Risks and ambiguities list",
    )
    evidence_references: list[EvidenceReference] = Field(
        default_factory=list,
        description="All grounded evidence citations from source documents",
    )
    confirmed_by_user: bool = Field(
        default=False,
        description="False until user explicitly reviews and accepts the specification",
    )
    confirmation_timestamp: str | None = Field(
        default=None,
        description="ISO-8601 UTC timestamp of explicit user confirmation",
    )

    @model_validator(mode="after")
    def sync_aliases(self) -> "ConfirmedProjectSpec":
        if not self.primary_goal and self.executive_summary:
            self.primary_goal = self.executive_summary
        elif not self.executive_summary and self.primary_goal:
            self.executive_summary = self.primary_goal
        return self
